import type { Film } from '../lib/types'

function slug(title: string, year: number): string {
  return (
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') + `-${year}`
  )
}

function f(
  title: string,
  year: number,
  director: string,
  country: string,
  lists: string[],
  services: string[],
): Film {
  return { id: slug(title, year), title, year, director, country, lists, services }
}

